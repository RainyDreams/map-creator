/**
 * 判断一段文字是否像国家/地区名（用于 Excel 导入时自动识别境外学生）。
 * 规则：常见留学目的地名单 + 「X国」「X洲」后缀模式。
 * 城市名打错字（如“北景”）不会误判——不在名单也不匹配后缀，仍按未定位处理。
 */
const COMMON_COUNTRIES = new Set([
  '美国', '英国', '加拿大', '澳大利亚', '澳洲', '新西兰', '新加坡', '日本', '韩国',
  '德国', '法国', '意大利', '西班牙', '荷兰', '瑞士', '瑞典', '挪威', '芬兰', '丹麦',
  '爱尔兰', '俄罗斯', '马来西亚', '泰国', '越南', '阿联酋', '卡塔尔', '以色列',
])

export function isLikelyCountryOrRegion(text: string): boolean {
  const t = text.trim().replace(/[（(].*$/, '')
  if (t === '') return false
  if (COMMON_COUNTRIES.has(t)) return true
  // 「XX国」「XX洲」后缀（美国/德国/欧洲等），但排除国内地名（中国/全国）
  if (t.length >= 2 && /[国洲]$/.test(t) && !PROVINCE_ALIASES[t] && t !== '中国' && t !== '全国') {
    return true
  }
  return false
}

/** 规范化省份名（支持短名/全称/带括号别名），匹配不到返回 null */
export function normalizeProvinceName(name: string): ProvinceName | null {
  const cleaned = name.trim().replace(/[（(].*$/, '')
  return PROVINCE_ALIASES[cleaned] ?? null
}

/** 全国地级市 → 省份完整映射（由 functions/api/_data/cities.json 同源生成，键含带/不带“市”两种写法） */
const ALL_CITY_TO_PROVINCE = cityProvinceJson as Record<string, string>

/** 由城市名查省份：先查常见城市静态表，再查全国地级市完整映射 */
export function provinceOfCity(city: string): ProvinceName | null {
  const cleaned = city.trim().replace(/市$/, '')
  if (cleaned === '') return null
  const hit = CITY_TO_PROVINCE[cleaned] ?? ALL_CITY_TO_PROVINCE[cleaned]
  return (hit as ProvinceName | undefined) ?? null
}

/** 由大学名推断城市（先精确，再去括号后缀，再模糊包含） */
export function inferCityFromUniversity(university: string): string | null {
  const name = university.trim()
  if (!name) return null
  // 括号里的校区城市优先，如“哈尔滨工业大学（威海）”
  const campusMatch = name.match(/[（(]([^（）()]+)[)）]/)
  const base = name.replace(/[（(].*$/, '').trim()
  if (campusMatch) {
    const campus = campusMatch[1].trim()
    if (CITY_TO_PROVINCE[campus]) return campus
    // 括号里不是城市名（如“深圳”是城市，但“华东”不是）则继续按主校名推断
  }
  if (UNIVERSITY_TO_CITY[base]) return UNIVERSITY_TO_CITY[base]
  // 模糊匹配：大学名包含某个已知校名
  for (const [uni, city] of Object.entries(UNIVERSITY_TO_CITY)) {
    if (base.includes(uni) || uni.includes(base)) return city
  }
  return null
}

/**
 * 解析条目所属省份：优先城市，其次大学名推断。
 * 返回 null 表示无法定位（该条目不会出现在地图上，录入页应提示）。
 */
export function resolveProvince(entry: { city?: string; university?: string }): ProvinceName | null {
  if (entry.city?.trim()) {
    const byCity = provinceOfCity(entry.city)
    if (byCity) return byCity
    // 用户可能直接填了省份名
    const asProvince = normalizeProvinceName(entry.city)
    if (asProvince) return asProvince
  }
  if (entry.university?.trim()) {
    const city = inferCityFromUniversity(entry.university)
    if (city) return provinceOfCity(city)
  }
  return null
}

/** 已诊断过的条目键，避免同一条目在每次渲染时重复刷屏 */
const diagnosedUnlocated = new Set<string>()

/**
 * 定位失败诊断：在控制台输出为什么这个条目无法在地图上定位（每条目只输出一次）。
 * 输出尝试过的所有路径与中间结果，便于用户反馈时直接复制。
 */
export function diagnoseUnlocated(entry: { name?: string; city?: string; university?: string }): void {
  const key = `${entry.name ?? ''}|${entry.city ?? ''}|${entry.university ?? ''}`
  if (diagnosedUnlocated.has(key)) return
  diagnosedUnlocated.add(key)
  const city = entry.city?.trim() ?? ''
  const university = entry.university?.trim() ?? ''
  const attempts: string[] = []
  if (city) {
    attempts.push(
      `① 按城市「${city}」查全国地级市表：${provinceOfCity(city) ?? '未命中'}`,
      `② 按省份名解析「${city}」：${normalizeProvinceName(city) ?? '未命中'}`,
    )
  } else {
    attempts.push('① 城市为空，跳过城市查询')
  }
  if (university) {
    const inferred = inferCityFromUniversity(university)
    attempts.push(
      `③ 按大学「${university}」推断城市：${inferred ?? '未命中（该大学不在内置高校表中，建议手动补填城市）'}`,
    )
  } else {
    attempts.push('③ 大学为空，无法推断')
  }
  console.warn(
    `[定位] 「${entry.name ?? '（未命名）'}」无法在地图上定位：\n  ${attempts.join('\n  ')}\n  建议：在城市栏通过「省份 → 城市」下拉选择，或手动输入地级市名（如“赤峰”）。`,
  )
}
